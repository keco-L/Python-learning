#深拷贝 ：数据完全不共享
#外出和内层的
#深拷贝只会影响自己本身 不会对其他有所影响
import copy 
list1=[1,2,3,4,5,[99,80,76]]
list2=copy.deepcopy(list1)
print("list1的地址：",id(list1))#list1的地址： 2596222008320
print("list2的地址：",id(list2))#list2的地址： 2596223565440

print('list1初始时：',list1)
print('list2初始时：',list2)
list1.append('我服了')
print('list1外层添加时：',list1)#list1外层添加时： [1, 2, 3, 4, 5, [99, 80, 76], '我服了']
print('list2外层添加时：',list2)#list2外层添加时： [1, 2, 3, 4, 5, [99, 80, 76]]
list1[5].append('嘻嘻')
print('list1内层添加时：',list1)#list1内层添加时： [1, 2, 3, 4, 5, [99, 80, 76, '嘻嘻'], '我服了']
print('list2内层添加时：',list2)#list2内层添加时： [1, 2, 3, 4, 5, [99, 80, 76]]
#无论List1做什么措施，list2都没有发生变化
